"""
Exports a small version of the gesture model so the micro:bit recognises gestures by itself
(TinyML). Trains a compact Random Forest on every recording in data/raw/, packs its trees into
a byte block, writes that into microbit/gesture_makecode.js, and builds microbit/gesture_classifier.hex.

The micro:bit computes the same 96 features as gesture_features.py and lets each tree vote.
Before writing anything, this script re-runs that exact on-board calculation in Python
(double-precision features, packed Float32 thresholds, majority vote) and reports how often
it agrees with the laptop's model.

Usage:
  python gesture/export_microbit.py              # largest model that fits; writes the firmware and builds the .hex
  python gesture/export_microbit.py --flash      # ...and copies the .hex onto the micro:bit
  python gesture/export_microbit.py --trees 30 --depth 8   # a specific size instead
"""

import os
import re
import json
import time
import shutil
import struct
import argparse
import subprocess
import numpy as np

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold

from gesture_features import GESTURE_NAMES, LED_CODES, extract_features
import train

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MICROBIT_DIR = os.path.join(BASE_DIR, "microbit")
FIRMWARE_PATH = os.path.join(MICROBIT_DIR, "gesture_makecode.js")
HEX_PATH = os.path.join(MICROBIT_DIR, "gesture_classifier.hex")
INFO_PATH = os.path.join(MICROBIT_DIR, "onboard_model.json")
BUILD_DIR = os.path.join(MICROBIT_DIR, "build")
BUILD_PROJECT = os.path.join(BUILD_DIR, "project")

# Packed node: feature index (255 = leaf), Float32 threshold, UInt16 right child (or class for a leaf)
NODE_FORMAT = '<BfH'
NODE_BYTES = struct.calcsize(NODE_FORMAT)
LEAF = 255
# Model data has to fit in the micro:bit V2's flash beside the MakeCode runtime and the rest of the
# program: about 160 KB is free, so stay well under it
MAX_MODEL_BYTES = 128 * 1024
# Tried from largest to smallest; the first that fits MAX_MODEL_BYTES is used.
# On 672 recordings, 120 trees of depth 12 (log2 features per split) reached 99.0% in 111.6 KB.
CANDIDATES = [(150, 12), (120, 12), (100, 12), (80, 12), (60, 12), (50, 10), (30, 8), (20, 8), (10, 6)]
MODEL_START = '// ==== ON-BOARD MODEL: generated by gesture/export_microbit.py - do not edit by hand ===='
MODEL_END = '// ==== END ON-BOARD MODEL ===='


def small_forest(trees: int, depth: int) -> RandomForestClassifier:
    # log2(96) = 6 features tried per split: more varied trees, which helped more than extra trees did
    return RandomForestClassifier(n_estimators=trees, max_depth=depth, max_features='log2', class_weight='balanced',
                                  random_state=42, n_jobs=-1)


def float32_at_most(value: float) -> float:
    """The largest Float32 not above value, so `x <= threshold` splits exactly as scikit-learn does."""
    f = np.float32(value)
    if float(f) > value:
        f = np.nextafter(f, np.float32(-np.inf))
    return float(f)


def pack_forest(forest: RandomForestClassifier) -> bytes:
    """Root index per tree, then every node in pre-order (left child = next node)."""
    nodes, roots = [], []
    for estimator in forest.estimators_:
        tree = estimator.tree_

        def emit(i):
            index = len(nodes)
            if tree.children_left[i] == -1:
                nodes.append([LEAF, 0.0, int(np.argmax(tree.value[i][0]))])
                return index
            nodes.append([int(tree.feature[i]), float32_at_most(tree.threshold[i]), 0])
            emit(tree.children_left[i])
            nodes[index][2] = emit(tree.children_right[i])
            return index

        roots.append(emit(0))
    if len(nodes) > 65535:
        raise ValueError(f"{len(nodes)} nodes is more than a UInt16 index can address")
    return struct.pack(f'<{len(roots)}H', *roots) + b''.join(struct.pack(NODE_FORMAT, *n) for n in nodes)


def predict_packed(model: bytes, n_trees: int, n_classes: int, features: np.ndarray):
    """Exactly what predictOnBoard() does on the micro:bit. Returns (class index, vote share)."""
    votes = [0] * n_classes
    nodes_start = 2 * n_trees
    for t in range(n_trees):
        node = struct.unpack_from('<H', model, 2 * t)[0]
        while True:
            feature, threshold, right = struct.unpack_from(NODE_FORMAT, model, nodes_start + node * NODE_BYTES)
            if feature == LEAF:
                votes[right] += 1
                break
            node = node + 1 if features[feature] <= threshold else right
    best = max(range(n_classes), key=lambda c: (votes[c], -c))  # first class with the most votes
    return best, votes[best] / n_trees


def board_accuracy(recordings, y, trees, depth, folds=5):
    """Cross-validated accuracy of the packed model, scored the way the micro:bit predicts."""
    X32 = np.array([extract_features(r) for r in recordings])
    X64 = np.array([extract_features(r, dtype=np.float64) for r in recordings])
    folds = min(folds, min(np.unique(y, return_counts=True)[1]))
    correct = 0
    for train_idx, test_idx in StratifiedKFold(folds, shuffle=True, random_state=42).split(X32, y):
        forest = small_forest(trees, depth).fit(X32[train_idx], y[train_idx])
        model = pack_forest(forest)
        for i in test_idx:
            best, _ = predict_packed(model, trees, len(forest.classes_), X64[i])
            correct += forest.classes_[best] == y[i]
    return correct / len(y)


def write_firmware(model: bytes, classes, trees: int, depth: int, threshold: float, n_recordings: int):
    codes = ', '.join(f'"{LED_CODES.get(c, "CUSTOM")}"' for c in classes)
    names = ', '.join(GESTURE_NAMES.get(c, c) for c in classes)
    hex_lines = '\n'.join(model[i:i + 64].hex() for i in range(0, len(model), 64))
    n_nodes = (len(model) - 2 * trees) // NODE_BYTES
    block = (f"{MODEL_START}\n"
             f"// {trees} trees (max depth {depth}), {n_nodes:,} nodes, {len(model):,} bytes - "
             f"trained {time.strftime('%Y-%m-%d %H:%M')} on {n_recordings} recordings\n"
             f"// Classes: {names}\n"
             f"const MODEL_TREES = {trees}\n"
             f"const MODEL_THRESHOLD = {threshold}\n"
             f"const MODEL_CLASSES: string[] = [{codes}]\n"
             f"const MODEL = hex`\n{hex_lines}\n`\n"
             f"{MODEL_END}")
    with open(FIRMWARE_PATH, encoding='utf-8') as f:
        source = f.read()
    pattern = re.compile(re.escape(MODEL_START) + '.*?' + re.escape(MODEL_END), re.DOTALL)
    if not pattern.search(source):
        raise RuntimeError(f"Model markers not found in {FIRMWARE_PATH}")
    with open(FIRMWARE_PATH, 'w', encoding='utf-8') as f:
        f.write(pattern.sub(lambda _: block, source))


def build_hex() -> bool:
    """Compile the firmware with the local MakeCode compiler (set up once in microbit/build).
    Built for the micro:bit V2 only: the V1 has too little flash for the model."""
    if not os.path.isdir(os.path.join(BUILD_DIR, "node_modules", "pxt-microbit")):
        print("\nMakeCode compiler not set up, so no .hex was built. Either paste microbit/gesture_makecode.js "
              "into MakeCode and click Download, or set the compiler up once with:\n"
              "  cd gesture/microbit/build && npm install && npx pxt target microbit && cd project && npx pxt install")
        return False
    shutil.copy(FIRMWARE_PATH, os.path.join(BUILD_PROJECT, "main.ts"))
    print("Building the .hex with MakeCode...")
    shutil.rmtree(os.path.join(BUILD_PROJECT, "built"), ignore_errors=True)
    # build/project/pxt.json sets "disablesVariants": ["mbdal"], so MakeCode skips the V1 image
    result = subprocess.run("npx pxt build", cwd=BUILD_PROJECT, shell=True, capture_output=True, text=True)
    built = os.path.join(BUILD_PROJECT, "built", "binary.hex")
    errors = [line for line in (result.stdout + result.stderr).splitlines() if 'error' in line.lower()]
    if result.returncode != 0 or errors or not os.path.exists(built):
        print("MakeCode build failed:\n" + '\n'.join(errors or (result.stdout + result.stderr).splitlines()[-15:]))
        return False
    shutil.copy(built, HEX_PATH)
    print(f"Built {HEX_PATH}")
    return True


def find_microbit_drive():
    for letter in "DEFGHIJKLMNOPQRSTUVWXYZ":
        if os.path.exists(f"{letter}:\\DETAILS.TXT") and os.path.exists(f"{letter}:\\MICROBIT.HTM"):
            return f"{letter}:\\"
    return None


def main():
    parser = argparse.ArgumentParser(description="Export the gesture model to run on the micro:bit itself.")
    parser.add_argument('--trees', type=int, help="Number of trees (default: the largest that fits).")
    parser.add_argument('--depth', type=int, help="Maximum tree depth (use with --trees).")
    parser.add_argument('--threshold', type=float, default=0.3, help="Vote share below which the micro:bit shows ? (default 0.3).")
    parser.add_argument('--flash', action='store_true', help="Copy the built .hex onto the micro:bit.")
    parser.add_argument('--exclude', nargs='*', default=[], help="Gesture ids to leave out (e.g. c_b).")
    args = parser.parse_args()

    recordings, y, people = train.load_recordings(train.DATA_DIR)
    keep = ~np.isin(y, args.exclude)
    recordings, y, people = [r for r, k in zip(recordings, keep) if k], y[keep], people[keep]
    if len(set(y)) < 2:
        raise SystemExit("Need recordings of at least 2 gestures - record some on the dashboard first.")
    X32 = np.array([extract_features(r) for r in recordings])
    X64 = np.array([extract_features(r, dtype=np.float64) for r in recordings])
    print(f"Loaded {len(y)} recordings of {len(set(y))} gestures from {len(set(people))} "
          f"{'person' if len(set(people)) == 1 else 'people'}.")

    candidates = [(args.trees, args.depth)] if args.trees else CANDIDATES
    for trees, depth in candidates:
        forest = small_forest(trees, depth).fit(X32, y)
        model = pack_forest(forest)
        if len(model) <= MAX_MODEL_BYTES or args.trees:
            break
        print(f"  {trees} trees, depth {depth}: {len(model) / 1024:.0f} KB - too big")
    classes = list(forest.classes_)
    n_nodes = (len(model) - 2 * trees) // NODE_BYTES
    print(f"Using {trees} trees, max depth {depth}: {n_nodes:,} nodes, {len(model) / 1024:.1f} KB "
          f"(limit {MAX_MODEL_BYTES // 1024} KB)")

    # Does the micro:bit's calculation give the same answers as scikit-learn on the same model?
    board = [classes[predict_packed(model, trees, len(classes), x)[0]] for x in X64]
    agreement = float(np.mean(np.array(board) == forest.predict(X32)))
    print(f"On-board calculation agrees with scikit-learn on {agreement * 100:.1f}% of recordings")

    print("Cross-validating the on-board model (5 folds)...")
    accuracy = board_accuracy(recordings, y, trees, depth)
    print(f"On-board model accuracy on unseen recordings: {accuracy * 100:.1f}%")

    write_firmware(model, classes, trees, depth, args.threshold, len(y))
    info = {
        'classes': classes,
        'trees': trees,
        'max_depth': depth,
        'nodes': n_nodes,
        'bytes': len(model),
        'threshold': args.threshold,
        'cv_accuracy': accuracy,
        'agreement_with_sklearn': agreement,
        'recordings': int(len(y)),
        'people': sorted(set(people)),
        'exported_at': time.strftime('%Y-%m-%d %H:%M'),
    }
    with open(INFO_PATH, 'w', encoding='utf-8') as f:
        json.dump(info, f, indent=2)
    print(f"Wrote the model into {FIRMWARE_PATH}")

    if build_hex() and args.flash:
        drive = find_microbit_drive()
        if drive:
            shutil.copy(HEX_PATH, drive)
            print(f"Flashed {drive} - wait for READY on the micro:bit.")
        else:
            print("No micro:bit drive found - plug it in, or drag the .hex onto the MICROBIT drive yourself.")


if __name__ == '__main__':
    main()
